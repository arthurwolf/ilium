"""Host-side import dispatch of the plugin host, generated from the same WIT model as the mirrors.

Called by tools/gen_plugin_api.py (build_outputs); not a command of its own.

Output:

    ilium-plugin-host/src/imports/generated_dispatch.rs
        * `IMPORT_INTERFACES`: every interface of ilium:host, ilium:primitives and ilium:anim
          that has functions, with its component instance name, its functions (WIT name,
          parameter count, whether it returns a value) and the functions the dynamic linker
          cannot serve yet (they take or return a resource handle).
        * `ImportSet`: one optional boxed `Host<Interface>` implementation per interface. The
          runtime fills it per plugin instance from the grants and the kernel facade and
          puts it in the store data.
        * `ImportSet::call`: routes (instance name, function name, JSON arguments) to the
          trait method. Arguments are deserialized into the serde mirror types; the result
          is serialized back. The linker closure lifts and lowers between component values
          and JSON (ilium-plugin-host/src/wasm_guest.rs `lift` / `lower`).

Resource methods and functions with a handle in their signature are listed as unlinked: the
dynamic value bridge has no resource support (contract section 10, wave two).
"""

HOST_CRATE = "ilium-plugin-host"
DISPATCH_PATH = f"{HOST_CRATE}/src/imports/generated_dispatch.rs"
IMPORT_DIRECTORIES = ("host", "primitives", "anim")


class Dispatch:
    def __init__(self, api, model, renderer, glue):
        self.api = api
        self.model = model
        self.renderer = renderer
        self.glue = glue

    def interfaces(self):
        result = []
        for key in self.model.order:
            interface = self.model.interfaces[key]
            if interface.directory not in IMPORT_DIRECTORIES:
                continue
            if not self.glue.methods(interface):
                continue
            result.append(interface)
        return result

    def split(self, interface):
        """(linked functions, unlinked WIT names)."""
        linked = []
        unlinked = []
        for function, resource in self.glue.methods(interface):
            if resource is not None:
                if function["kind"] == "constructor":
                    unlinked.append(f"[constructor]{resource['name']}")
                elif function["kind"] == "static":
                    unlinked.append(f"[static]{resource['name']}.{function['name']}")
                else:
                    unlinked.append(f"[method]{resource['name']}.{function['name']}")
                continue
            types = [parameter_type for _, parameter_type in function["parameters"]]
            if function["result"] is not None:
                types.append(function["result"])
            if any(self.glue.has_handle(interface, wit_type) for wit_type in types):
                unlinked.append(function["name"])
                continue
            linked.append(function)
        return linked, unlinked

    def trait_path(self, interface):
        trait = self.renderer.trait_name(interface)
        return f"ilium_plugin_api::generated::{interface.directory}::{interface.module}::{trait}"

    def dispatch_function(self, interface, linked):
        name = f"dispatch_{interface.module}"
        lines = [
            f"fn {name}(",
            f"    host: &mut (dyn {self.trait_path(interface)} + Send),",
            "    function: &str,",
            "    arguments: Vec<Value>,",
            ") -> Result<Value, DispatchError> {",
            "    let mut arguments = arguments.into_iter();",
            "    let value = match function {",
        ]
        for function in linked:
            method = self.api.rust_value_name(function["name"])
            count = len(function["parameters"])
            lines.append(f"        \"{function['name']}\" => {{")
            for index in range(count):
                lines.append(f"            let a{index} = argument(&mut arguments, {index})?;")
            call = f"host.{method}({', '.join(f'a{index}' for index in range(count))})"
            lines.append(f"            result({call})?")
            lines.append("        }")
        lines.extend([
            "        _ => return Err(DispatchError::UnknownFunction),",
            "    };",
            "    if arguments.next().is_some() {",
            "        return Err(DispatchError::ArgumentCount);",
            "    }",
            "    Ok(value)",
            "}",
            "",
        ])
        return lines

    def file(self, header_lines):
        interfaces = self.interfaces()
        lines = list(header_lines)
        lines.extend([
            "//! Dispatch of component imports onto the `Host<Interface>` traits.",
            "//! Generated by tools/gen_plugin_host_dispatch.py from wit/. Never edit by hand.",
            "#![allow(clippy::too_many_lines, clippy::let_unit_value, clippy::unit_arg)]",
            "",
            "use serde::de::DeserializeOwned;",
            "use serde::Serialize;",
            "use serde_json::Value;",
            "",
            "/// Why an import call could not be routed. Each one is a guest ABI violation or a",
            "/// host wiring gap, never a plugin-visible error value.",
            "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
            "pub enum DispatchError {",
            "    /// The interface is not part of this instance's import set.",
            "    NotLinked,",
            "    /// The interface has no function of that name.",
            "    UnknownFunction,",
            "    /// Too few or too many arguments.",
            "    ArgumentCount,",
            "    /// An argument does not have the shape of its WIT type; the index is zero-based.",
            "    Argument(usize),",
            "    /// The result could not be serialized.",
            "    Result,",
            "}",
            "",
            "impl DispatchError {",
            "    /// The stable trap code reported for this failure.",
            "    pub fn code(self) -> &'static str {",
            "        match self {",
            "            DispatchError::NotLinked => \"host.capability-not-requested\",",
            "            _ => \"trap.abi\",",
            "        }",
            "    }",
            "}",
            "",
            "/// One function of an import interface.",
            "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
            "pub struct ImportFunction {",
            "    /// The WIT function name.",
            "    pub name: &'static str,",
            "    /// The number of parameters.",
            "    pub parameters: usize,",
            "    /// Whether the function returns a value.",
            "    pub has_result: bool,",
            "}",
            "",
            "/// One import interface of the plugin worlds.",
            "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
            "pub struct ImportInterface {",
            "    /// The component instance name, for example `ilium:host/log@0.1.0`.",
            "    pub instance: &'static str,",
            "    /// The WIT package, for example `ilium:host`.",
            "    pub package: &'static str,",
            "    /// The interface name, for example `log`.",
            "    pub name: &'static str,",
            "    /// The functions the linker serves.",
            "    pub functions: &'static [ImportFunction],",
            "    /// The functions with a resource handle in their signature: not linked yet.",
            "    pub unlinked: &'static [&'static str],",
            "}",
            "",
            "/// Every import interface with at least one function, in manual order.",
            "pub static IMPORT_INTERFACES: &[ImportInterface] = &[",
        ])
        for interface in interfaces:
            linked, unlinked = self.split(interface)
            lines.append("    ImportInterface {")
            lines.append(f"        instance: \"{self.glue.wit_id(interface)}\",")
            lines.append(f"        package: \"{self.api.PACKAGE_OF_DIRECTORY[interface.directory]}\",")
            lines.append(f"        name: \"{interface.name}\",")
            lines.append("        functions: &[")
            for function in linked:
                has_result = "true" if function["result"] is not None else "false"
                lines.append(
                    f"            ImportFunction {{ name: \"{function['name']}\", "
                    f"parameters: {len(function['parameters'])}, has_result: {has_result} }},"
                )
            lines.append("        ],")
            names = ", ".join(f"\"{name}\"" for name in unlinked)
            lines.append(f"        unlinked: &[{names}],")
            lines.append("    },")
        lines.extend([
            "];",
            "",
            "/// The table entry of a component instance name.",
            "pub fn import_interface(instance: &str) -> Option<&'static ImportInterface> {",
            "    IMPORT_INTERFACES.iter().find(|interface| interface.instance == instance)",
            "}",
            "",
            "/// The host implementations one plugin instance may call. `None` means the interface",
            "/// is not granted or has no backing in this process.",
            "#[derive(Default)]",
            "pub struct ImportSet {",
        ])
        for interface in interfaces:
            lines.append(f"    /// `{self.glue.wit_id(interface)}`.")
            lines.append(f"    pub {interface.module}: Option<Box<dyn {self.trait_path(interface)} + Send>>,")
        lines.extend([
            "}",
            "",
            "impl std::fmt::Debug for ImportSet {",
            "    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {",
            "        formatter.debug_struct(\"ImportSet\").field(\"linked\", &self.linked()).finish()",
            "    }",
            "}",
            "",
            "impl ImportSet {",
            "    /// The instance names that have an implementation.",
            "    pub fn linked(&self) -> Vec<&'static str> {",
            "        let mut names = Vec::new();",
        ])
        for interface in interfaces:
            lines.append(f"        if self.{interface.module}.is_some() {{")
            lines.append(f"            names.push(\"{self.glue.wit_id(interface)}\");")
            lines.append("        }")
        lines.extend([
            "        names",
            "    }",
            "",
            "    /// Removes the implementation of one interface. Returns whether it was present.",
            "    pub fn remove(&mut self, instance: &str) -> bool {",
            "        match instance {",
        ])
        for interface in interfaces:
            lines.append(f"            \"{self.glue.wit_id(interface)}\" => self.{interface.module}.take().is_some(),")
        lines.extend([
            "            _ => false,",
            "        }",
            "    }",
            "",
            "    /// Calls one import function with JSON arguments and returns its JSON result",
            "    /// (`null` for a function without a result).",
            "    pub fn call(",
            "        &mut self,",
            "        instance: &str,",
            "        function: &str,",
            "        arguments: Vec<Value>,",
            "    ) -> Result<Value, DispatchError> {",
            "        match instance {",
        ])
        for interface in interfaces:
            lines.append(f"            \"{self.glue.wit_id(interface)}\" => match self.{interface.module}.as_deref_mut() {{")
            lines.append(f"                Some(host) => dispatch_{interface.module}(host, function, arguments),")
            lines.append("                None => Err(DispatchError::NotLinked),")
            lines.append("            },")
        lines.extend([
            "            _ => Err(DispatchError::NotLinked),",
            "        }",
            "    }",
            "}",
            "",
            "fn argument<T: DeserializeOwned>(",
            "    arguments: &mut std::vec::IntoIter<Value>,",
            "    index: usize,",
            ") -> Result<T, DispatchError> {",
            "    let value = arguments.next().ok_or(DispatchError::ArgumentCount)?;",
            "    serde_json::from_value(value).map_err(|_| DispatchError::Argument(index))",
            "}",
            "",
            "fn result<T: Serialize>(value: T) -> Result<Value, DispatchError> {",
            "    serde_json::to_value(value).map_err(|_| DispatchError::Result)",
            "}",
            "",
        ])
        for interface in interfaces:
            linked, _ = self.split(interface)
            lines.extend(self.dispatch_function(interface, linked))
        lines.extend([
            "#[cfg(test)]",
            "mod tests {",
            "    use super::{import_interface, DispatchError, ImportSet, IMPORT_INTERFACES};",
            "",
            "    #[test]",
            "    fn instance_names_are_unique_and_versioned() {",
            "        let mut names: Vec<&str> = IMPORT_INTERFACES.iter().map(|entry| entry.instance).collect();",
            "        let count = names.len();",
            "        names.sort_unstable();",
            "        names.dedup();",
            "        assert_eq!(names.len(), count);",
            f"        assert!(names.iter().all(|name| name.ends_with(\"@{self.api.VERSION}\")));",
            "    }",
            "",
            "    #[test]",
            "    fn an_empty_set_links_nothing_and_refuses_every_call() {",
            "        let mut set = ImportSet::default();",
            "        assert!(set.linked().is_empty());",
            "        for interface in IMPORT_INTERFACES {",
            "            assert_eq!(",
            "                set.call(interface.instance, \"anything\", Vec::new()),",
            "                Err(DispatchError::NotLinked)",
            "            );",
            "        }",
            "    }",
            "",
            "    #[test]",
            "    fn the_log_interface_has_its_one_function() {",
            f"        let log = import_interface(\"ilium:host/log@{self.api.VERSION}\").expect(\"log is an import\");",
            "        assert_eq!(log.functions.len(), 1);",
            "        assert_eq!(log.functions[0].name, \"log\");",
            "        assert_eq!(log.functions[0].parameters, 2);",
            "        assert!(!log.functions[0].has_result);",
            "    }",
            "}",
        ])
        return "\n".join(lines) + "\n"


def outputs(api, model, renderer, glue, tree_sha256):
    """{relative path: unformatted text} of the host dispatch file."""
    dispatch = Dispatch(api, model, renderer, glue)
    return {DISPATCH_PATH: dispatch.file(api.header(tree_sha256, DISPATCH_PATH))}
