/// REQ: PORT:ilium-client/src/background_animation/surface.rs::unconfigured_surface_refuses_before_spawning_and_preserves_error
#[test]
fn port_unconfigured_surface_refuses_before_spawning_and_preserves_error() {
    let mut scene = fake_scene("waves", 24, 12);
    let before = scene.frame(braille_frame(24, 12, 500));
    for bad in ["{not json", "not json at all", "{\"a\":"] {
        assert!(!scene.reconfigure(bad), "{bad:?} is refused");
    }
    let after = scene.frame(braille_frame(24, 12, 500));
    assert_eq!(
        before.text(),
        after.text(),
        "a refused configuration leaves the previous one in force"
    );
}
